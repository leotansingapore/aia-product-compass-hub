// Auto-suggested reference photos per case id. Generated by
// tools/match-photos-to-cases.py using product-mention + specific-dollar
// matches between the case's metadata and each photo's Telegram context +
// AI description. Strong-signal-only — generic tag-overlap matches are
// filtered out to keep false positives low.
