#!/usr/bin/env node
// node scripts/og/build-og.mjs [--changed] [--no-db]
//
// Writes scripts/og/pages.mjs (path -> title, description, card) and renders the cards it
// names into public/og/<card>.jpg, so a shared academy link unfurls as its own page instead
// of the site card. api/page-og.ts serves pages.mjs to preview crawlers at request time.
//
// Sources: the section rows in routes.mjs, the day and assignment files in docs/, and the
// products and categories tables. Products are not readable with the anon key, so the
// service key comes from SUPABASE_SERVICE_ROLE_KEY (in .env.local); --no-db, or no key,
// keeps the product rows already in pages.mjs instead of dropping them.
//
// --changed redraws only cards whose HTML moved since scripts/og/cards.lock.json, so a weekly
// run commits nothing when nothing changed. Output is committed: the Vercel build has no
// browser. Playwright comes from the repo's devDependencies.

import { chromium } from '@playwright/test';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { cardHtml, ROOT } from './card.mjs';
import { collectPages } from './routes.mjs';

const OUT = path.join(ROOT, 'public/og');
const PAGES_FILE = path.join(ROOT, 'scripts/og/pages.mjs');
const LOCK = path.join(ROOT, 'scripts/og/cards.lock.json');
const TMP = path.join(ROOT, 'node_modules/.og-cards');

const args = process.argv.slice(2);
const changedOnly = args.includes('--changed');

function loadEnv() {
  for (const f of ['.env.local', '.env']) {
    const p = path.join(ROOT, f);
    if (!existsSync(p)) continue;
    for (const line of readFileSync(p, 'utf8').split('\n')) {
      const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
      if (m && !process.env[m[1]]) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
    }
  }
}

async function fetchTable(table, select) {
  const url = process.env.VITE_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (args.includes('--no-db') || !url || !key) return null;
  const r = await fetch(`${url}/rest/v1/${table}?select=${select}&order=sort_order`, {
    headers: { apikey: key, Authorization: `Bearer ${key}` },
  });
  if (!r.ok) throw new Error(`${table}: ${r.status} ${await r.text()}`);
  return r.json();
}

const previous = existsSync(PAGES_FILE) ? (await import(pathToFileURL(PAGES_FILE).href)).default : {};

loadEnv();
const products = await fetchTable('products', 'id,title,description,published,category_id,training_videos');
const categories = await fetchTable('categories', 'id,name,description,published');
if (!products) console.warn('no SUPABASE_SERVICE_ROLE_KEY: keeping the product and category rows already in pages.mjs');

const { pages, cards } = collectPages({ products, categories, previous });

// Every card a page names must be drawn, and every drawn card must belong to a page.
for (const [p, page] of Object.entries(pages)) {
  if (!cards[page.card]) throw new Error(`${p} names card ${page.card}, which has no design`);
}

const hash = (html) => createHash('sha1').update(html.split(ROOT).join('')).digest('hex').slice(0, 16);
const lock = existsSync(LOCK) ? JSON.parse(readFileSync(LOCK, 'utf8')) : {};
// A `reuse` card is kept from the last build (no database this run): never redrawn.
const todo = Object.entries(cards).filter(([slug, card]) => {
  if (card.reuse) return false;
  if (!changedOnly) return true;
  return !existsSync(path.join(OUT, `${slug}.jpg`)) || lock[slug] !== hash(cardHtml(card));
});

mkdirSync(OUT, { recursive: true });
mkdirSync(TMP, { recursive: true });
if (todo.length) {
  const browser = await chromium.launch().catch(() => chromium.launch({ channel: 'chrome' }));
  const page = await browser.newPage({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 1 });
  for (const [slug, card] of todo) {
    const html = cardHtml(card);
    const tmp = path.join(TMP, `${slug}.html`);
    writeFileSync(tmp, html);
    await page.goto(pathToFileURL(tmp).href);
    await page.waitForFunction(() => document.body.dataset.fit, null, { timeout: 15000 });
    await page.waitForFunction(() => Array.from(document.images).every((i) => i.complete && i.naturalWidth > 0));
    await page.screenshot({ path: path.join(OUT, `${slug}.jpg`), type: 'jpeg', quality: 84 });
    lock[slug] = hash(html);
  }
  await browser.close();
}

const sortedLock = Object.fromEntries(
  Object.keys(cards).sort().map((k) => [k, cards[k].reuse ? lock[k] : lock[k] ?? hash(cardHtml(cards[k]))]),
);
writeFileSync(LOCK, `${JSON.stringify(sortedLock, null, 2)}\n`);

const sortedPages = Object.fromEntries(Object.keys(pages).sort().map((k) => [k, pages[k]]));
writeFileSync(
  PAGES_FILE,
  `// Generated by scripts/og/build-og.mjs. Edit scripts/og/routes.mjs or the content, then rerun it.\n` +
    `export default ${JSON.stringify(sortedPages, null, 2)};\n`,
);
console.log(`${Object.keys(pages).length} pages, ${Object.keys(cards).length} cards, ${todo.length} drawn`);

